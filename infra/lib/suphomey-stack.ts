import * as path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CfnOutput, Duration, RemovalPolicy, Stack, TimeZone, type StackProps } from 'aws-cdk-lib';
import * as cloudfront from 'aws-cdk-lib/aws-cloudfront';
import * as origins from 'aws-cdk-lib/aws-cloudfront-origins';
import * as cloudwatch from 'aws-cdk-lib/aws-cloudwatch';
import * as cwActions from 'aws-cdk-lib/aws-cloudwatch-actions';
import * as ec2 from 'aws-cdk-lib/aws-ec2';
import * as ecs from 'aws-cdk-lib/aws-ecs';
import * as ecsPatterns from 'aws-cdk-lib/aws-ecs-patterns';
import * as elbv2 from 'aws-cdk-lib/aws-elasticloadbalancingv2';
import * as logs from 'aws-cdk-lib/aws-logs';
import * as rds from 'aws-cdk-lib/aws-rds';
import * as scheduler from 'aws-cdk-lib/aws-scheduler';
import * as schedulerTargets from 'aws-cdk-lib/aws-scheduler-targets';
import * as sns from 'aws-cdk-lib/aws-sns';
import * as subscriptions from 'aws-cdk-lib/aws-sns-subscriptions';
import type { Construct } from 'constructs';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');

export type SuphomeyStackProps = StackProps & {
  /**
   * ID of the CloudFront origin-facing managed prefix list in the target region
   * (com.amazonaws.global.cloudfront.origin-facing). The load balancer only
   * accepts traffic from CloudFront, so users cannot bypass the CDN.
   */
  cloudFrontPrefixListId: string;
  /** Optional address for alarm emails. */
  alarmEmail?: string;
  /** Build images from the repo (default). Tests pass a placeholder to skip Docker. */
  image?: { web: ecs.ContainerImage; ingest: ecs.ContainerImage };
};

/**
 * Production deployment on AWS. Mirrors the Vercel + Neon setup one to one:
 *
 *   Vercel Edge Network -> CloudFront
 *   Vercel Functions     -> ECS Fargate service behind an Application Load Balancer
 *   Neon Postgres        -> RDS PostgreSQL in isolated subnets
 *   Vercel Cron          -> EventBridge Scheduler running the ingest image on Fargate
 *   Env variables        -> Secrets Manager (generated by RDS)
 */
export class SuphomeyStack extends Stack {
  constructor(scope: Construct, id: string, props: SuphomeyStackProps) {
    super(scope, id, props);

    // ---- Network: public subnets for the ALB, private (with NAT) for tasks, isolated for the database.
    const vpc = new ec2.Vpc(this, 'Vpc', {
      maxAzs: 2,
      // One NAT gateway keeps cost down; tasks need outbound access to data.gov.sg.
      natGateways: 1,
      subnetConfiguration: [
        { name: 'public', subnetType: ec2.SubnetType.PUBLIC },
        { name: 'app', subnetType: ec2.SubnetType.PRIVATE_WITH_EGRESS },
        { name: 'data', subnetType: ec2.SubnetType.PRIVATE_ISOLATED },
      ],
    });

    // ---- Database
    const dbSecurityGroup = new ec2.SecurityGroup(this, 'DbSecurityGroup', { vpc, description: 'Postgres, reachable only from app tasks' });
    const database = new rds.DatabaseInstance(this, 'Database', {
      engine: rds.DatabaseInstanceEngine.postgres({ version: rds.PostgresEngineVersion.VER_17_9 }),
      instanceType: ec2.InstanceType.of(ec2.InstanceClass.T4G, ec2.InstanceSize.MICRO),
      vpc,
      vpcSubnets: { subnetType: ec2.SubnetType.PRIVATE_ISOLATED },
      securityGroups: [dbSecurityGroup],
      databaseName: 'suphomey',
      // RDS generates the password and stores host, port, user and password in Secrets Manager.
      credentials: rds.Credentials.fromGeneratedSecret('suphomey'),
      allocatedStorage: 20,
      maxAllocatedStorage: 50,
      storageType: rds.StorageType.GP3,
      storageEncrypted: true,
      publiclyAccessible: false,
      multiAz: false,
      backupRetention: Duration.days(7),
      deletionProtection: true,
      removalPolicy: RemovalPolicy.SNAPSHOT,
      cloudwatchLogsExports: ['postgresql'],
    });
    const dbSecret = database.secret!;

    // Every task reads the same PG* variables; node-postgres picks them up (packages/db/src/client.ts).
    const dbEnvironment = { PGSSLMODE: 'verify-full' };
    const dbSecrets = {
      PGHOST: ecs.Secret.fromSecretsManager(dbSecret, 'host'),
      PGPORT: ecs.Secret.fromSecretsManager(dbSecret, 'port'),
      PGDATABASE: ecs.Secret.fromSecretsManager(dbSecret, 'dbname'),
      PGUSER: ecs.Secret.fromSecretsManager(dbSecret, 'username'),
      PGPASSWORD: ecs.Secret.fromSecretsManager(dbSecret, 'password'),
    };

    const images = props.image ?? {
      web: ecs.ContainerImage.fromAsset(REPO_ROOT, { target: 'web' }),
      ingest: ecs.ContainerImage.fromAsset(REPO_ROOT, { target: 'ingest' }),
    };

    // ---- Web app on Fargate behind an ALB
    const cluster = new ecs.Cluster(this, 'Cluster', { vpc, containerInsightsV2: ecs.ContainerInsights.ENABLED });
    const webLogs = new logs.LogGroup(this, 'WebLogs', { retention: logs.RetentionDays.ONE_MONTH, removalPolicy: RemovalPolicy.DESTROY });

    const web = new ecsPatterns.ApplicationLoadBalancedFargateService(this, 'Web', {
      cluster,
      cpu: 512,
      memoryLimitMiB: 1024,
      desiredCount: 2,
      // Start new tasks before stopping old ones, so deploys never reduce capacity.
      minHealthyPercent: 100,
      maxHealthyPercent: 200,
      taskSubnets: { subnetType: ec2.SubnetType.PRIVATE_WITH_EGRESS },
      publicLoadBalancer: true,
      // Opened explicitly below, to CloudFront only.
      openListener: false,
      circuitBreaker: { rollback: true },
      taskImageOptions: {
        image: images.web,
        containerPort: 3000,
        environment: dbEnvironment,
        secrets: dbSecrets,
        logDriver: ecs.LogDrivers.awsLogs({ streamPrefix: 'web', logGroup: webLogs }),
      },
    });
    web.targetGroup.configureHealthCheck({ path: '/api/health', healthyHttpCodes: '200', interval: Duration.seconds(15) });
    web.loadBalancer.connections.allowFrom(ec2.Peer.prefixList(props.cloudFrontPrefixListId), ec2.Port.tcp(80), 'CloudFront only');
    for (const sg of web.service.connections.securityGroups) dbSecurityGroup.addIngressRule(sg, ec2.Port.tcp(5432), 'Web to Postgres');

    const scaling = web.service.autoScaleTaskCount({ minCapacity: 2, maxCapacity: 6 });
    scaling.scaleOnCpuUtilization('Cpu', { targetUtilizationPercent: 60 });

    // ---- CDN. Caching follows the app's Cache-Control headers (s-maxage on API reads),
    // with query strings in the cache key because the API is driven by them.
    const distribution = new cloudfront.Distribution(this, 'Cdn', {
      comment: 'suphomey',
      defaultBehavior: {
        origin: new origins.LoadBalancerV2Origin(web.loadBalancer, { protocolPolicy: cloudfront.OriginProtocolPolicy.HTTP_ONLY }),
        viewerProtocolPolicy: cloudfront.ViewerProtocolPolicy.REDIRECT_TO_HTTPS,
        allowedMethods: cloudfront.AllowedMethods.ALLOW_GET_HEAD_OPTIONS,
        cachePolicy: cloudfront.CachePolicy.USE_ORIGIN_CACHE_CONTROL_HEADERS_QUERY_STRINGS,
        originRequestPolicy: cloudfront.OriginRequestPolicy.ALL_VIEWER_EXCEPT_HOST_HEADER,
        compress: true,
      },
      priceClass: cloudfront.PriceClass.PRICE_CLASS_200,
    });

    // ---- Daily refresh: the ingest image on Fargate, triggered by EventBridge Scheduler.
    const ingestLogs = new logs.LogGroup(this, 'IngestLogs', { retention: logs.RetentionDays.THREE_MONTHS, removalPolicy: RemovalPolicy.DESTROY });
    const ingestTask = new ecs.FargateTaskDefinition(this, 'IngestTask', { cpu: 1024, memoryLimitMiB: 3072 });
    ingestTask.addContainer('ingest', {
      image: images.ingest,
      // Migrate first so a deploy with a new migration is picked up by the next run.
      command: ['sh', '-c', 'pnpm db:migrate && pnpm ingest'],
      environment: dbEnvironment,
      secrets: dbSecrets,
      logging: ecs.LogDrivers.awsLogs({ streamPrefix: 'ingest', logGroup: ingestLogs }),
    });
    const ingestSecurityGroup = new ec2.SecurityGroup(this, 'IngestSecurityGroup', { vpc, description: 'Ingest task: outbound to data.gov.sg and Postgres' });
    dbSecurityGroup.addIngressRule(ingestSecurityGroup, ec2.Port.tcp(5432), 'Ingest to Postgres');

    new scheduler.Schedule(this, 'DailyRefresh', {
      description: 'Refresh resale, rentals, preschool vacancies, hawker closures and dengue areas',
      schedule: scheduler.ScheduleExpression.cron({ minute: '0', hour: '3', timeZone: TimeZone.ASIA_SINGAPORE }),
      target: new schedulerTargets.EcsRunFargateTask(cluster, {
        taskDefinition: ingestTask,
        vpcSubnets: { subnetType: ec2.SubnetType.PRIVATE_WITH_EGRESS },
        securityGroups: [ingestSecurityGroup],
        retryAttempts: 2,
      }),
    });

    // ---- Alarms
    const alarms = new sns.Topic(this, 'Alarms');
    if (props.alarmEmail) alarms.addSubscription(new subscriptions.EmailSubscription(props.alarmEmail));
    const notify = new cwActions.SnsAction(alarms);
    const alarm = (
      id: string,
      metric: cloudwatch.IMetric,
      threshold: number,
      description: string,
      comparisonOperator = cloudwatch.ComparisonOperator.GREATER_THAN_OR_EQUAL_TO_THRESHOLD,
    ) =>
      new cloudwatch.Alarm(this, id, {
        metric,
        threshold,
        comparisonOperator,
        evaluationPeriods: 3,
        alarmDescription: description,
        treatMissingData: cloudwatch.TreatMissingData.NOT_BREACHING,
      }).addAlarmAction(notify);

    alarm('Web5xx', web.loadBalancer.metrics.httpCodeTarget(elbv2.HttpCodeTarget.TARGET_5XX_COUNT, { period: Duration.minutes(5) }), 10, 'App returned 10+ server errors in 5 minutes');
    alarm('WebUnhealthy', web.targetGroup.metrics.unhealthyHostCount({ period: Duration.minutes(1) }), 1, 'A web task is failing its health check');
    alarm('DbCpu', database.metricCPUUtilization({ period: Duration.minutes(5) }), 80, 'Postgres CPU above 80%');
    alarm(
      'DbStorage',
      database.metricFreeStorageSpace({ period: Duration.minutes(15), statistic: 'Minimum' }),
      2 * 1024 ** 3,
      'Postgres has less than 2 GiB free',
      cloudwatch.ComparisonOperator.LESS_THAN_THRESHOLD,
    );

    new CfnOutput(this, 'Url', { value: `https://${distribution.distributionDomainName}` });
    new CfnOutput(this, 'DatabaseSecretArn', { value: dbSecret.secretArn });
    new CfnOutput(this, 'IngestTaskDefinition', { value: ingestTask.taskDefinitionArn });
    new CfnOutput(this, 'ClusterName', { value: cluster.clusterName });
  }
}
